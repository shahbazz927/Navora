// Read-only validation for the Global Study university database.
// Run: node scripts/global-study/validate.mjs
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { COUNTRIES } from '../../src/data/studyAbroad.js';
import { OWNERSHIP_VALUES, TUITION_STATUS_VALUES, VERIFICATION_VALUES } from './sources.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const canonicalFile = path.join(root, 'data/global-study/universities.json');
const generatedFile = path.join(root, 'src/data/globalUniversities.js');
const reportFile = path.join(root, 'reports/global-study-validation.json');

const records = JSON.parse(await readFile(canonicalFile, 'utf8'));
const countryIds = new Set(COUNTRIES.map((c) => c.id));
const errors = [];
const warnings = [];

function err(record, message) {
  errors.push(`${record.id || '(no id)'}: ${message}`);
}

function isHttps(value) {
  try {
    return new URL(value).protocol === 'https:';
  } catch {
    return false;
  }
}

const ids = new Set();
const domains = new Set();
const names = new Set();

for (const r of records) {
  if (!r.id || typeof r.id !== 'string') err(r, 'missing id');
  if (!r.name || typeof r.name !== 'string') err(r, 'missing name');
  if (!countryIds.has(r.countryId)) err(r, `unknown countryId ${r.countryId}`);
  if (!r.city) err(r, 'missing city');
  if (!OWNERSHIP_VALUES.includes(r.ownership)) err(r, `invalid ownership ${r.ownership}`);
  if (!r.type) err(r, 'missing type');
  if (!r.institutionKind) err(r, 'missing institutionKind');
  if (!isHttps(r.website)) err(r, `website is not https: ${r.website}`);
  if (!r.domain) err(r, 'missing domain');
  if (!r.ownershipSource || !isHttps(r.ownershipSource)) err(r, `invalid ownershipSource ${r.ownershipSource}`);
  if (!Array.isArray(r.sourceUrls) || r.sourceUrls.length < 2) err(r, 'needs at least two sourceUrls');
  if (Array.isArray(r.sourceUrls) && !r.sourceUrls.every(isHttps)) err(r, 'sourceUrls must all be https');
  if (!TUITION_STATUS_VALUES.includes(r.tuitionStatus)) err(r, `invalid tuitionStatus ${r.tuitionStatus}`);
  if (r.tuitionStatus === 'published' && !r.tuitionByProgram) err(r, 'published tuition without tuitionByProgram');
  if (!VERIFICATION_VALUES.includes(r.verificationStatus)) err(r, `invalid verificationStatus ${r.verificationStatus}`);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(r.lastVerified || '')) err(r, `invalid lastVerified ${r.lastVerified}`);
  if (r.reputation != null && typeof r.reputation !== 'string') err(r, 'reputation must be string or null');
  if (!Array.isArray(r.strengths)) err(r, 'strengths must be array');
  if (!Array.isArray(r.programs)) err(r, 'programs must be array');
  if (!Array.isArray(r.scholarships)) err(r, 'scholarships must be array');

  if (ids.has(r.id)) err(r, `duplicate id ${r.id}`);
  ids.add(r.id);

  const domainKey = `${r.countryId}|${r.domain}`;
  if (domains.has(domainKey)) err(r, `duplicate domain ${domainKey}`);
  domains.add(domainKey);

  const nameKey = `${r.countryId}|${r.name.toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim()}`;
  if (names.has(nameKey)) err(r, `duplicate name ${r.name}`);
  names.add(nameKey);
}

const generated = await readFile(generatedFile, 'utf8');
const expectedGenerated = `// AUTO-GENERATED by scripts/global-study/seed.mjs. Do not edit by hand.\n// Source: data/global-study/universities.json\nexport const UNIVERSITIES = ${JSON.stringify(records, null, 2)};\n`;
if (generated !== expectedGenerated) {
  errors.push('src/data/globalUniversities.js is out of date; run node scripts/global-study/seed.mjs');
}

const countries = COUNTRIES.map((c) => {
  const list = records.filter((r) => r.countryId === c.id);
  const publicCount = list.filter((r) => r.ownership === 'Public').length;
  const privateCount = list.filter((r) => r.ownership === 'Private').length;
  if (publicCount < 20) warnings.push(`${c.name}: only ${publicCount} public universities`);
  if (privateCount < 20) warnings.push(`${c.name}: only ${privateCount} private universities`);
  return {
    countryId: c.id,
    country: c.name,
    total: list.length,
    public: publicCount,
    private: privateCount,
    publicShortfall: Math.max(0, 20 - publicCount),
    privateShortfall: Math.max(0, 20 - privateCount),
    meetsTarget: publicCount >= 20 && privateCount >= 20,
    verified: list.filter((r) => r.verificationStatus === 'verified').length,
    publishedTuition: list.filter((r) => r.tuitionStatus === 'published').length,
    kinds: list.reduce((acc, r) => {
      acc[r.institutionKind] = (acc[r.institutionKind] || 0) + 1;
      return acc;
    }, {}),
  };
});

const report = {
  generatedAt: new Date().toISOString().slice(0, 10),
  countryCount: COUNTRIES.length,
  totalUniversities: records.length,
  publicTotal: records.filter((r) => r.ownership === 'Public').length,
  privateTotal: records.filter((r) => r.ownership === 'Private').length,
  errors,
  warnings,
  countries,
};

await writeFile(reportFile, `${JSON.stringify(report, null, 2)}\n`, 'utf8');

console.log(`Countries: ${report.countryCount}`);
console.log(`Universities: ${report.totalUniversities} (${report.publicTotal} public, ${report.privateTotal} private)`);
console.table(countries.map((c) => ({
  Country: c.country,
  Public: c.public,
  Private: c.private,
  Total: c.total,
  'Public shortfall': c.publicShortfall,
  'Private shortfall': c.privateShortfall,
  Target: c.meetsTarget ? 'MET' : 'SHORT',
})));
if (warnings.length) {
  console.log(`\nShortfalls (${warnings.length}):`);
  for (const warning of warnings) console.log(`- ${warning}`);
}
if (errors.length) {
  console.error(`\nValidation errors (${errors.length}):`);
  for (const message of errors) console.error(`- ${message}`);
  process.exit(1);
}
console.log('\nValidation passed.');
