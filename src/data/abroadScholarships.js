// ── Helpers ────────────────────────────────────────────────────────────────
export function getAbroadScholarshipsForIndianNationals() {
  return ABROAD_SCHOLARSHIPS.filter(s => (s.eligible_nationalities || []).includes('India')
    && s.status !== 'expired' && s.verification_status !== 'EXPIRED');
}

export function getAbroadScholarshipsByCountry(country) {
  return ABROAD_SCHOLARSHIPS.filter(s => (s.country || '').toLowerCase() === String(country || '').toLowerCase());
}

export function getAbroadScholarshipById(id) {
  return ABROAD_SCHOLARSHIPS.find(s => s.id === id) || null;
}

export function getAbroadScholarshipsForLevel(level) {
  const l = String(level || '').toUpperCase();
  return ABROAD_SCHOLARSHIPS.filter(s => (s.education_levels || []).some(x => x.toUpperCase() === l));
}

export function getAbroadScholarshipsForField(field) {
  const f = String(field || '').toLowerCase();
  return ABROAD_SCHOLARSHIPS.filter(s => (s.eligible_fields || []).some(x => x.toLowerCase().includes(f)));
}

/** Countries that actually have at least one record, in editorial order, with counts */
export function getScholarshipCountriesWithData() {
  const counts = {};
  ABROAD_SCHOLARSHIPS.forEach(s => { counts[s.country] = (counts[s.country] || 0) + 1; });
  const ordered = [
    ...ABROAD_COUNTRY_ORDER.filter(c => counts[c]),
    ...Object.keys(counts).filter(c => !ABROAD_COUNTRY_ORDER.includes(c)),
  ];
  return ordered.map(name => ({
    name,
    code: ABROAD_COUNTRY_META[name]?.code || '',
    region: ABROAD_COUNTRY_META[name]?.region || '',
    count: counts[name],
    availableToIndians: getAbroadScholarshipsByCountry(name).filter(s => (s.eligible_nationalities || []).includes('India')).length,
    fullyFunded: getAbroadScholarshipsByCountry(name).filter(s => s.funding_type === 'Fully Funded').length,
  }));
}

/** { country: [records] } grouped in ABROAD_COUNTRY_ORDER */
export function groupAbroadScholarshipsByCountry() {
  const groups = {};
  getScholarshipCountriesWithData().forEach(c => { groups[c.name] = getAbroadScholarshipsByCountry(c.name); });
  return groups;
}

/** One-line summary per country, derived from the data (never hand-written promises) */
export function getCountryScholarshipSummary(country) {
  const list = getAbroadScholarshipsByCountry(country);
  if (!list.length) return null;
  const forIndians = list.filter(s => (s.eligible_nationalities || []).includes('India') && s.status !== 'expired');
  const full = forIndians.filter(s => s.funding_type === 'Fully Funded');
  const types = Array.from(new Set(forIndians.map(s => s.scholarship_type).filter(Boolean)));
  return { total: list.length, forIndians: forIndians.length, fullyFunded: full.length, types };
}
