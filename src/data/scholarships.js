export function getScholarshipsForInstitution(slug) {
  const ids = COLLEGE_SCHOLARSHIP_LINKS.filter(l => l.college_slug === slug).map(l => l.scholarship_id);
  return SCHOLARSHIPS.filter(s => ids.includes(s.id));
}
export function getScholarshipById(id) { return SCHOLARSHIPS.find(s=>s.id===id) || null; }

