// Helper: Filter Master Colleges
export function searchMasterColleges({
  query = '',
  level = 'All', // 'All' | 'UG' | 'PG' | 'Both'
  course = 'All',
  collegeType = 'All',
  district = 'All',
  limit = 50
} = {}) {
  const norm = (s) => (s || '').toLowerCase().replace(/[^a-z0-9]/g, '');
  const cTarget = norm(course);
  const tTarget = (collegeType || '').toLowerCase().trim();
  const dTarget = (district || '').toLowerCase().trim();

  return MASTER_COLLEGES.filter((col) => {
    // 1. Level Filter
    if (level === 'UG' && !col.ugAvailable) return false;
    if (level === 'PG' && !col.pgAvailable) return false;
    if (level === 'Both' && (!col.ugAvailable || !col.pgAvailable)) return false;

    // 2. Course Filter
    if (course !== 'All') {
      const allCourseStr = [...(col.ugCourses || []), ...(col.pgCourses || [])].join(' ');
      const allNorm = norm(allCourseStr);

      if (cTarget === 'btech' || cTarget === 'be') {
        if (!allNorm.includes('btech') && !allNorm.includes('be')) return false;
      } else if (cTarget === 'ba') {
        const hasBa = [...(col.ugCourses || [])].some(c => {
          const cl = c.toLowerCase().trim();
          return cl === 'b.a.' || cl === 'b.a' || cl === 'ba';
        });
        if (!hasBa) return false;
      } else if (cTarget === 'llb' || cTarget === 'law') {
        if (!allNorm.includes('llb') && !allNorm.includes('law') && !allNorm.includes('llm')) return false;
      } else if (cTarget === 'mba') {
        if (!allNorm.includes('mba') && !allNorm.includes('pgdm')) return false;
      } else if (cTarget === 'mtech' || cTarget === 'me') {
        if (!allNorm.includes('mtech') && !allNorm.includes('me')) return false;
      } else {
        if (!allNorm.includes(cTarget)) return false;
      }
    }

    // 3. College Type Filter
    if (collegeType !== 'All') {
      const colT = (col.collegeType || '').toLowerCase();
      if (!colT.includes(tTarget)) return false;
    }

    // 4. District Filter
    if (district !== 'All') {
      const colD = (col.district || '').toLowerCase();
      const colCity = (col.city || '').toLowerCase();
      if (!colD.includes(dTarget) && !colCity.includes(dTarget)) return false;
    }

    // 5. Intelligent Query Search Filter
    if (query && query.trim()) {
      if (!matchesCollegeSearch(col, query)) {
        return false;
      }
    }

    return true;
  }).slice(0, limit);
}

